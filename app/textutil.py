"""文本显示相关的工具。

目前只有一个函数：按**显示宽度**把长标题截断成图例能放下的长度。

★ 为什么这个函数值得单独一个模块 + 一份注释：

  项目早期画 Mock 数据的 Top20 条形图时，y 轴标签用了最朴素的 `t[:14]`。
  图上出现了三条**看起来一模一样**的「绿联 磁吸手机指环扣 金属 …」，
  销量却是 45794 / 7595 / 7022。

  第一反应是"数据重复了"，去查库才发现 Top20 里 19 个标题都是唯一的：
  那三条是**不同颜色的 SKU**，而颜色恰好写在标题的最后两个字，
  被按字符数的截断切掉了。图看起来在说谎，其实是截断在说谎。

  所以这里有两个决定，各自对应那次事故的一半：

  1. **按显示宽度而不是字符数截断。**
     一个中文字符占两个英文字符的宽度。`t[:14]` 在纯中文标题上
     实际显示 28 个字符宽，在纯英文标题上只有 14——同一张图里
     两行标签的视觉长度差一倍，而"能放下多少"是由视觉长度决定的。

  2. **保留尾部，而不是砍掉尾部。**
     中文商品标题的结构高度固定：`品牌 + 品类 + 规格 + 颜色/款式`。
     区分 SKU 的信息（颜色、容量、数量）**几乎总在最后**，
     而品牌和品类在前面已经重复过很多次了。
     砍尾巴正好把最有区分度的部分切掉，这是最坏的选择。

     所以默认取"头 + 省略号 + 尾"：`绿联 磁吸手机指环扣…深空灰`。
     一眼能看出是同一款的哪个颜色——这正是图例该干的事。


★★ 但这个策略有个反例，是给 API 写测试时撞出来的，必须记在这里 ★★

  上面那句"区分 SKU 的信息几乎总在最后"，对**我们自己生成的 Mock 标题**
  是对的（seed.py 的格式就是 `品牌 品类 规格 颜色`，颜色收尾）。
  但**真实 SMZDM 的标题不是这个形状**，SKU 后面还跟着一串营销语：

      "绿联 磁吸手机指环扣 金属 超薄 深空灰 商务款 送礼佳品"
                                                    ↑ 颜色在这里，不在末尾

  实测：budget=26/30/40 三种预算下，上面这条和它的"午夜黑"版本
  截出来的结果**完全相同**——因为尾部分到的那点预算全被
  "商务款 送礼佳品" 吃掉了。也就是说，保尾部**并不足以**保证 SKU 可区分。

  试过加大预算，没用——实测数据：

      budget=26  A/B 都是 '绿联 磁吸手机指… 送礼佳品'                不可区分
      budget=30  A/B 都是 '绿联 磁吸手机指环…款 送礼佳品'            不可区分
      budget=40  A/B 都是 '绿联 磁吸手机指环扣 金… 商务款 送礼佳品'   不可区分
      budget=60  未截断，给的是完整标题                              可区分（但这不是"截断"的功劳）

  根因是颜色后面固定跟着 2 个 token（"商务款/送礼佳品"），
  而尾部的宽度配额是按比例分的——只要还在截断，就够不到它。

  → **结论：没有任何一种固定截断策略能保证"不同 SKU 一定长得不一样"。**
     想靠调截断规则解决这个问题，方向本身就错了。

  → 真正的修法是架构层面的，而且比调参数简单得多：
     **`title_short` 只负责让图例放得下，而它绝不能是标题出现的唯一位置。**
     接口同时返回完整的 `title`，前端把它放进 ECharts 的 tooltip。
     鼠标移到哪根柱子上就能看到完整标题——信息一点没丢。

     这正是那条回归测试（tests/test_textutil.py）真正在守的东西：
     它不是"截断后一定可区分"（那是做不到的），
     而是"截断后的宽度不超预算，且尾部信息别被无谓地丢掉"。

  → 如果将来还想提升图例本身的可读性，下一步是把标题里的营销噪声
     （送礼/佳品/包邮…）先按停用词表洗掉再截断——
     洗掉之后颜色就会重新落到尾部。但那需要在这里引入分词，
     而分词的开销和"改一个词云文件会影响图表标签"的耦合都不小，
     所以现在没做，先靠 tooltip 兜住。
"""

from __future__ import annotations

# 判定"双宽字符"的码点下界。
#
# ★ 0x2E80 这个阈值是刻意取在 CJK 部首区之前，而不是常用的 0x4E00（汉字起始）。
#   因为中文标题里除了汉字还有大量**全角标点**（，。：（）【】）和
#   全角字母数字（１２３ＡＢ），它们肉眼看上去同样是双宽，
#   但码点落在 0x3000~0x33FF 和 0xFF00~0xFFEF 区间。
#   用 0x4E00 当阈值的话，这些字符会被算成 1 个单位，
#   于是一条「【限时】充电宝（白色）」的估算宽度会比实际少 5~6 个单位——
#   图上表现为标签明显比其他行宽，还是会溢出。
#
#   用一个大而化之的 0x2E80 覆盖 CJK 部首 + 假名 + 全角标点，
#   宁可把少数边缘字符算宽（大不了提前一个字符截断），
#   也不要算窄（会溢出图例区域）。
_DOUBLE_WIDTH_FROM = 0x2E80


def display_width(text: str) -> int:
    """文本的显示宽度：CJK 及全角标点算 2，其余算 1。"""
    return sum(2 if ord(ch) >= _DOUBLE_WIDTH_FROM else 1 for ch in text)


def _take_head(text: str, budget: int) -> str:
    """从头开始取，直到再加一个字符就会超出 budget。"""
    out: list[str] = []
    width = 0
    for ch in text:
        w = 2 if ord(ch) >= _DOUBLE_WIDTH_FROM else 1
        if width + w > budget:
            break
        out.append(ch)
        width += w
    return "".join(out)


def _take_tail(text: str, budget: int) -> str:
    """从尾开始倒着取，直到再加一个字符就会超出 budget。"""
    out: list[str] = []
    width = 0
    for ch in reversed(text):
        w = 2 if ord(ch) >= _DOUBLE_WIDTH_FROM else 1
        if width + w > budget:
            break
        out.append(ch)
        width += w
    out.reverse()
    return "".join(out)


def elide_middle(text: str, budget: int = 26, head_ratio: float = 0.6) -> str:
    """把长文本截成 `头…尾`，总显示宽度不超过 budget。

    head_ratio 默认 0.6 —— 前面多留一点，因为品牌+品类承载了"这是什么"，
    尾部只需要放下"哪个 SKU"（通常两三个字）。

    ★ 保证：返回值的显示宽度一定 <= budget（省略号本身占 1 个单位）。
      调用方可以依赖这一点去算图例宽度，不用再截一次。

    ★ 不可能出现"截了但没省略号"的情况：
      head 和 tail 的宽度之和最多是 budget-1，而进到这里时
      text 的宽度必然 > budget，所以至少有一个字符被丢掉了。
    """
    # 先处理两种退化输入，顺序不能反：
    #   · budget <= 0 —— 传 0 或负数进来会让下面的减法算出负宽度。
    #     返回空串而不是抛异常，因为这个函数跑在接口的返回路径上，
    #     一个美化标签的工具不该有能力让整个请求 500。
    if budget <= 0:
        return ""

    # ★ "放得下就原样返回" 必须排在预算判断之前。
    #   否则 budget=1 时一个宽度为 1 的字符串会被换成省略号——
    #   明明装得下，却给了个"这里省略了东西"的假信号。
    if display_width(text) <= budget:
        return text

    avail = budget - 1  # 给省略号留 1 个单位

    # ★ 这一段是测试逼出来的，值得记一笔：
    #   原来的写法是 head/tail 各 `max(1, ...)` 保底一个字符，
    #   于是 budget=2 时算出来是 1 + 1(省略号) + 1 = 3，**超出了 budget**。
    #   等于给了一个"宽度不超过 budget"的假承诺。
    #
    #   修法：预算窄到放不下"头+尾"时，把全部预算让给尾部。
    #   让给尾部（返回 "…灰"）而不是头部（返回 "绿…"），
    #   是为了和本函数的核心承诺一致——区分 SKU 的信息在尾部，
    #   而 2 个单位的宽度本来也读不出品牌。
    if avail < 2:
        return "…" + _take_tail(text, avail)

    head_budget = max(1, int(avail * head_ratio))
    tail_budget = max(1, avail - head_budget)

    return _take_head(text, head_budget) + "…" + _take_tail(text, tail_budget)
